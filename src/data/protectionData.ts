export const calculateSummaryStats = () => {
  const totalKII = RAW_KII_DATA.length;
  const kiiMales = RAW_KII_DATA.filter(k => k.gender === 'ذكر').length;
  const kiiFemales = RAW_KII_DATA.filter(k => k.gender === 'أنثى').length;
  
  const totalFGD = RAW_FGD_DATA.length;
  const totalFGDParticipants = RAW_FGD_DATA.reduce((acc, curr) => acc + curr.totalParticipants, 0);
  const fgdMaleParticipants = RAW_FGD_DATA
    .filter(f => f.gender === 'ذكر')
    .reduce((acc, curr) => acc + curr.totalParticipants, 0);
  const fgdFemaleParticipants = RAW_FGD_DATA
    .filter(f => f.gender === 'أنثى')
    .reduce((acc, curr) => acc + curr.totalParticipants, 0);

  const totalObservations = RAW_OBSERVATION_DATA.length;
  const totalObservedIdp = RAW_OBSERVATION_DATA.reduce((acc, curr) => acc + curr.approxIdpCount, 0);
  const totalObservedWomenChildren = RAW_OBSERVATION_DATA.reduce((acc, curr) => acc + curr.approxWomenChildrenCount, 0);

  return {
    totalKII,
    kiiMales,
    kiiFemales,
    kiiMalePct: Math.round((kiiMales / totalKII) * 100),
    kiiFemalePct: Math.round((kiiFemales / totalKII) * 100),
    totalFGD,
    totalFGDParticipants,
    fgdMaleParticipants,
    fgdFemaleParticipants,
    fgdMalePct: Math.round((fgdMaleParticipants / totalFGDParticipants) * 100),
    fgdFemalePct: Math.round((fgdFemaleParticipants / totalFGDParticipants) * 100),
    totalObservations,
    totalObservedIdp,
    totalObservedWomenChildren,
  };
};
